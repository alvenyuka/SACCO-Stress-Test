"""Write outputs/results.json and the two README charts from the engine's own results.

Every figure the README quotes comes from outputs/results.json, which this script writes from a fresh engine
run (seed 42, 2,000 loans), so the prose cannot drift from the numbers.

Run: python make_figures.py
"""
import json
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from stress_test_engine import SCENARIOS, PortfolioGenerator, StressTestEngine  # noqa: E402

SEED, N_LOANS = 42, 2000
EQUITY_SHARE = 0.15   # the engine's capital assumption: equity is 15% of outstanding loans before losses
MIN_CAR = 0.10        # the 10% minimum capital ratio the report tests against
ORDER = ["base", "adverse", "severe"]


def build_results():
    portfolio = PortfolioGenerator(seed=SEED).generate(n_loans=N_LOANS)
    results = StressTestEngine(portfolio).run_all_scenarios()
    outstanding = results["base"]["portfolio"]["total_outstanding"]
    equity = outstanding * EQUITY_SHARE
    scenarios = {}
    for key in ORDER:
        p = results[key]["portfolio"]
        equity_after = equity - p["total_ecl"]
        scenarios[key] = {
            "name": SCENARIOS[key].name,
            "probability_weight": p["probability"],
            "severity_score": p["severity_score"],
            "total_ecl_kes": round(p["total_ecl"], 2),
            "provision_rate": p["aggregate_provision_rate"],
            "capital_ratio_after_losses": equity_after / outstanding,
            "capital_shortfall_to_minimum_kes": round(max(0.0, MIN_CAR * outstanding - equity_after), 2),
        }
    sectors = {name: {"ecl_kes": round(v["ecl"], 2), "provision_rate": v["provision_rate"]}
               for name, v in results["adverse"]["sectors"].items()}
    weighted = results["weighted_ecl"]
    return {
        "seed": SEED,
        "n_loans": N_LOANS,
        "data": "synthetic portfolio generated by PortfolioGenerator; not real SACCO data",
        "total_outstanding_kes": outstanding,
        "assumed_equity_share": EQUITY_SHARE,
        "minimum_capital_ratio": MIN_CAR,
        "scenarios": scenarios,
        "probability_weighted": {"total_ecl_kes": round(weighted["total_ecl"], 2),
                                 "provision_rate": weighted["provision_rate"]},
        "adverse_by_sector": dict(sorted(sectors.items(), key=lambda kv: -kv[1]["provision_rate"])),
    }


def draw(res):
    os.makedirs("figures", exist_ok=True)
    names = [res["scenarios"][k]["name"] for k in ORDER]
    ecl = [res["scenarios"][k]["total_ecl_kes"] / 1e6 for k in ORDER]
    car = [res["scenarios"][k]["capital_ratio_after_losses"] * 100 for k in ORDER]

    fig, (a1, a2) = plt.subplots(1, 2, figsize=(11, 4.2))
    a1.bar(names, ecl, color=["#4C78A8", "#F58518", "#E45756"])
    for i, v in enumerate(ecl):
        a1.text(i, v, f"KES {v:.2f}M", ha="center", va="bottom", fontsize=9)
    a1.set_title("Expected credit loss by scenario")
    a1.set_ylabel("KES millions")
    a2.bar(names, car, color=["#4C78A8", "#F58518", "#E45756"])
    a2.axhline(MIN_CAR * 100, color="black", linestyle="--", linewidth=1)
    a2.text(2.45, MIN_CAR * 100 + 0.3, "10% minimum", ha="right", fontsize=9)
    for i, v in enumerate(car):
        a2.text(i, v, f"{v:.1f}%", ha="center", va="bottom", fontsize=9)
    a2.set_title("Capital ratio after losses (equity assumed at 15%)")
    a2.set_ylabel("%")
    fig.tight_layout()
    fig.savefig("figures/ecl_and_capital_by_scenario.png", dpi=130)
    plt.close(fig)

    sec = res["adverse_by_sector"]
    labels = list(sec)[::-1]
    rates = [sec[s]["provision_rate"] * 100 for s in labels]
    fig, ax = plt.subplots(figsize=(7, 4.2))
    ax.barh(labels, rates, color="#F58518")
    for i, v in enumerate(rates):
        ax.text(v, i, f" {v:.2f}%", va="center", fontsize=9)
    ax.set_title("Adverse scenario: provision rate by borrower sector")
    ax.set_xlabel("ECL as % of outstanding")
    fig.tight_layout()
    fig.savefig("figures/sector_provision_adverse.png", dpi=130)
    plt.close(fig)


if __name__ == "__main__":
    res = build_results()
    os.makedirs("outputs", exist_ok=True)
    with open("outputs/results.json", "w", encoding="utf-8") as f:
        json.dump(res, f, indent=2)
    draw(res)
    print("Wrote outputs/results.json, figures/ecl_and_capital_by_scenario.png, figures/sector_provision_adverse.png")
